export const priceBounds = { min: 0, max: Math.ceil(Math.max(...products.map((p) => p.price)) / 500) * 500 }
export const bestsellers = products.filter((p) => p.bestseller)
export const featured = products.filter((p) => p.featured)
export const newArrivals = products.filter((p) => p.isNew)
export const relatedTo = (product, limit = 4) =>
  products.filter((p) => p.id !== product.id).sort((a, b) => {
    const s = (x) => (x.category === product.category ? 2 : 0) + (x.collection === product.collection ? 2 : 0) + (x.finish === product.finish ? 1 : 0)
    return s(b) - s(a)
  }).slice(0, limit)
export const formatINR = (n) => '₹' + Number(n).toLocaleString('en-IN', { maximumFractionDigits: 0 })
